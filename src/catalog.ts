function getTemplateGroup(title: string, category: string): CatalogService["templateGroup"] {
  if (!templateKeywords.test(title)) return null;
  if (/عرض|PowerPoint|مناقشة/.test(title)) return "عروض";
  if (/Poster|بوستر|Infographic|غلاف|شهادة|بطاقة|دعوة|منشور|شعار|مخطط|Timeline|Diagram/.test(title)) return "تصاميم";
  if (/CV|Portfolio|وظيفي|منحة|Motivation|Statement|Cover Letter/.test(title)) return "سيرة مهنية";
  if (/استمارة|وثيقة|مستمسكات|أرشيف|تسجيل/.test(title) || category === "الوثائق والمعاملات") return "وثائق";
  if (/منصة|نظام|بوابة|صفحة|موقع|مشروع Web/.test(title)) return "تقنية";
  return "تقارير";
}

